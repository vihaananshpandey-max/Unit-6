public class Dog {
    private String name;
    private String breed;
    private int age;

    public String getName() {
        return name;
    }

    public void setName(String rename) {
        name = rename;
    }

    public String getBreed() {
        return breed;
    }

    public void setBreed(String newBreed) {
        breed = newBreed;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int newAge) {
        age = newAge;
    }
}
